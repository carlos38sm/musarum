-- Bandeja de canciones compartidas entre usuarios de la red. Patrick le
-- envía una canción a Carlos → aparece en la pantalla "Bandeja" de Carlos.
-- Mini inbox: nada de notificaciones push (Carlos no quiere Firebase);
-- el móvil consulta /inbox al abrir la app.

CREATE TABLE IF NOT EXISTS shared_songs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    from_user_id BIGINT NOT NULL,
    to_user_id   BIGINT NOT NULL,
    song_id      BIGINT NOT NULL,
    note         TEXT,
    read_at      TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT shared_songs_from_fk FOREIGN KEY (from_user_id) REFERENCES users (id),
    CONSTRAINT shared_songs_to_fk   FOREIGN KEY (to_user_id)   REFERENCES users (id),
    CONSTRAINT shared_songs_song_fk FOREIGN KEY (song_id)      REFERENCES songs (id)
);

CREATE INDEX IF NOT EXISTS idx_shared_songs_to_user
    ON shared_songs (to_user_id, created_at DESC);
