-- Fiestas musicales: una cola compartida en tiempo real entre users de la
-- casa. UNA party activa a la vez (constraint UNIQUE sobre closed_at IS NULL).
-- El HOST es quien reproduce; los demás ven la canción actual y pueden
-- añadir a la cola. El móvil polea /party/active cada pocos segundos.

CREATE TABLE IF NOT EXISTS listening_parties (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    host_user_id    BIGINT NOT NULL,
    current_song_id BIGINT,
    closed_at       TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT lp_host_fk FOREIGN KEY (host_user_id)    REFERENCES users (id),
    CONSTRAINT lp_song_fk FOREIGN KEY (current_song_id) REFERENCES songs (id)
);

-- Solo una party viva simultáneamente. Partial unique: solo evalúa filas
-- con closed_at nulo, por lo que las parties pasadas no bloquean nuevas.
CREATE UNIQUE INDEX IF NOT EXISTS ux_listening_parties_one_active
    ON listening_parties ((1))
    WHERE closed_at IS NULL;

CREATE TABLE IF NOT EXISTS listening_party_queue (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_id           BIGINT NOT NULL,
    "position"         INTEGER NOT NULL,
    song_id            BIGINT NOT NULL,
    added_by_user_id   BIGINT NOT NULL,
    added_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT lpq_party_fk FOREIGN KEY (party_id) REFERENCES listening_parties (id),
    CONSTRAINT lpq_song_fk  FOREIGN KEY (song_id)  REFERENCES songs (id),
    CONSTRAINT lpq_user_fk  FOREIGN KEY (added_by_user_id) REFERENCES users (id)
);
CREATE INDEX IF NOT EXISTS idx_lpq_party_position
    ON listening_party_queue (party_id, "position");

CREATE TABLE IF NOT EXISTS listening_party_members (
    party_id   BIGINT NOT NULL,
    user_id    BIGINT NOT NULL,
    joined_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (party_id, user_id),
    CONSTRAINT lpm_party_fk FOREIGN KEY (party_id) REFERENCES listening_parties (id),
    CONSTRAINT lpm_user_fk  FOREIGN KEY (user_id)  REFERENCES users (id)
);
