-- ============================================================================
--  V3 — carpetas de biblioteca gestionadas por el OWNER
-- ============================================================================
--  Modelo:
--    MUSARUM_MUSIC_PATH (del .env) es la carpeta "paraguas" montada en Docker.
--    Dentro vive la música del usuario, organizada en sub-carpetas que puede
--    activar/desactivar desde la app sin tocar YAML ni variables de entorno.
--
--    - path:   ruta absoluta a una carpeta. Debe estar bajo MUSARUM_MUSIC_PATH
--              para que Docker la vea (lo valida el service, no la DB).
--    - active: si está desactivada, el scanner la ignora. Permite "parar" de
--              escanear una zona sin perder la fila (favoritos / historial
--              de las canciones de dentro siguen vivos).
-- ============================================================================

CREATE TABLE library_folders (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    path        VARCHAR(1024) NOT NULL,
    active      BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT library_folders_path_unique UNIQUE (path)
);
