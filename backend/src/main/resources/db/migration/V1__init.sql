-- ============================================================================
--  Musarum — esquema inicial (baseline)
-- ============================================================================
--  Esta migración NO se aplica en instalaciones existentes: la tabla
--  flyway_schema_history ya tiene una fila BASELINE con version=1, así que
--  Flyway la salta. En una base de datos NUEVA, esta V1 crea todo el esquema
--  desde cero (mismo DDL que generaba Hibernate con ddl-auto=update).
--
--  A partir de aquí, cualquier cambio de esquema (añadir columna, tabla,
--  índice, etc.) se hace con V2__*.sql, V3__*.sql y así sucesivamente.
--  No se vuelve a tocar esta V1 nunca más.
-- ============================================================================

-- ── Usuarios ────────────────────────────────────────────────────────────────
CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    nick        VARCHAR(30)  NOT NULL,
    password    VARCHAR(60)  NOT NULL,
    user_role   VARCHAR(255) NOT NULL,
    CONSTRAINT users_nick_unique UNIQUE (nick),
    CONSTRAINT users_user_role_check CHECK (user_role IN ('OWNER', 'MEMBER'))
);

-- ── Artistas ────────────────────────────────────────────────────────────────
CREATE TABLE artists (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    name        VARCHAR(255) NOT NULL,
    name_key    VARCHAR(300),
    sort_name   VARCHAR(255),
    mb_id       VARCHAR(255),
    country     VARCHAR(255),
    begin_year  INTEGER,
    biography   TEXT,
    image_url   VARCHAR(255),
    type        VARCHAR(255)
);

-- ── Géneros ────────────────────────────────────────────────────────────────
CREATE TABLE genres (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    name        VARCHAR(255) NOT NULL,
    CONSTRAINT genres_name_unique UNIQUE (name)
);

-- ── Álbumes ────────────────────────────────────────────────────────────────
CREATE TABLE albums (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    title         VARCHAR(255) NOT NULL,
    title_key     VARCHAR(300),
    release_year  INTEGER,
    cover_url     VARCHAR(255),
    mb_id         VARCHAR(255),
    type          VARCHAR(255),
    artist_id     BIGINT NOT NULL,
    CONSTRAINT albums_artist_fk FOREIGN KEY (artist_id) REFERENCES artists (id)
);

-- ── Canciones ───────────────────────────────────────────────────────────────
CREATE TABLE songs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    title         VARCHAR(255) NOT NULL,
    audio_path    VARCHAR(255) NOT NULL,
    content_hash  VARCHAR(255) NOT NULL,
    duration_ms   INTEGER,
    track_number  INTEGER,
    disc_number   INTEGER,
    year          INTEGER,
    composer      VARCHAR(255),
    format        VARCHAR(255),
    bitrate       INTEGER,
    sample_rate   INTEGER,
    channels      INTEGER,
    file_size     BIGINT,
    bpm           INTEGER,
    musical_key   VARCHAR(255),
    replay_gain   DOUBLE PRECISION,
    isrc          VARCHAR(255),
    mb_id         VARCHAR(255),
    lyrics_path   VARCHAR(255),
    album_id      BIGINT,
    genre_id      BIGINT,
    CONSTRAINT songs_content_hash_unique UNIQUE (content_hash),
    CONSTRAINT songs_album_fk FOREIGN KEY (album_id) REFERENCES albums (id),
    CONSTRAINT songs_genre_fk FOREIGN KEY (genre_id) REFERENCES genres (id)
);

-- Relación N:M canciones ↔ artistas (song.artists)
CREATE TABLE song_artists (
    song_id   BIGINT NOT NULL,
    artist_id BIGINT NOT NULL,
    PRIMARY KEY (song_id, artist_id),
    CONSTRAINT song_artists_song_fk   FOREIGN KEY (song_id)   REFERENCES songs (id),
    CONSTRAINT song_artists_artist_fk FOREIGN KEY (artist_id) REFERENCES artists (id)
);

-- ── Playlists ──────────────────────────────────────────────────────────────
CREATE TABLE playlists (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    name        VARCHAR(255) NOT NULL,
    description TEXT,
    is_public   BOOLEAN NOT NULL,
    owner_id    BIGINT NOT NULL,
    CONSTRAINT playlists_owner_fk FOREIGN KEY (owner_id) REFERENCES users (id)
);

CREATE TABLE playlist_entries (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    "position"  INTEGER NOT NULL,
    playlist_id BIGINT NOT NULL,
    song_id     BIGINT NOT NULL,
    CONSTRAINT playlist_entries_unique UNIQUE (playlist_id, song_id),
    CONSTRAINT playlist_entries_playlist_fk FOREIGN KEY (playlist_id) REFERENCES playlists (id),
    CONSTRAINT playlist_entries_song_fk     FOREIGN KEY (song_id)     REFERENCES songs (id)
);

-- Relación N:M playlists ↔ colaboradores (user)
CREATE TABLE playlist_collaborators (
    playlist_id BIGINT NOT NULL,
    user_id     BIGINT NOT NULL,
    PRIMARY KEY (playlist_id, user_id),
    CONSTRAINT playlist_collaborators_playlist_fk FOREIGN KEY (playlist_id) REFERENCES playlists (id),
    CONSTRAINT playlist_collaborators_user_fk     FOREIGN KEY (user_id)     REFERENCES users (id)
);

-- ── Favoritos ──────────────────────────────────────────────────────────────
CREATE TABLE favorites (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    user_id     BIGINT NOT NULL,
    song_id     BIGINT NOT NULL,
    CONSTRAINT favorites_user_song_unique UNIQUE (user_id, song_id),
    CONSTRAINT favorites_user_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT favorites_song_fk FOREIGN KEY (song_id) REFERENCES songs (id)
);

-- ── Reproducciones ─────────────────────────────────────────────────────────
CREATE TABLE reproductions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    user_id     BIGINT NOT NULL,
    song_id     BIGINT NOT NULL
);

CREATE INDEX idx_reproductions_user_created ON reproductions (user_id, created_at);
CREATE INDEX idx_reproductions_user_song    ON reproductions (user_id, song_id);
